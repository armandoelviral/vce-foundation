from enum import StrEnum


class CaseLifecyclePhase(StrEnum):
    """Current operational phase of one retail case."""

    CASE_OPENED = "CASE_OPENED"
    RECOMMENDATION_AVAILABLE = "RECOMMENDATION_AVAILABLE"
    AWAITING_EXPERT_DECISION = "AWAITING_EXPERT_DECISION"
    EXPERT_DECISION_RECORDED = "EXPERT_DECISION_RECORDED"
    EXECUTION_RECORDED = "EXECUTION_RECORDED"
    OPERATIONAL_EVIDENCE_RECORDED = "OPERATIONAL_EVIDENCE_RECORDED"
